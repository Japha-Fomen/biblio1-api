-- =====================================================================
-- biblio1-api — V2 : comptes utilisateurs et roles (PostgreSQL)
-- Correspond aux entites Utilisateur et Role.
-- =====================================================================

CREATE TABLE utilisateur (
    id        BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    nom       VARCHAR(100) NOT NULL,
    prenom    VARCHAR(100) NOT NULL,
    email     VARCHAR(180) NOT NULL,
    password  VARCHAR(100) NOT NULL,
    actif     BOOLEAN      NOT NULL,
    PRIMARY KEY (id)
);

-- Table de la collection @ElementCollection des roles.
CREATE TABLE utilisateur_role (
    utilisateur_id BIGINT      NOT NULL,
    role           VARCHAR(30) NOT NULL,
    PRIMARY KEY (utilisateur_id, role),
    CONSTRAINT ck_utilisateur_role CHECK (role IN ('LECTEUR','BIBLIOTHECAIRE','ADMIN'))
);

-- ===== Contraintes d'unicite =====
ALTER TABLE utilisateur ADD CONSTRAINT uk_utilisateur_email UNIQUE (email);

-- ===== Cles etrangeres =====
ALTER TABLE utilisateur_role ADD CONSTRAINT fk_utilisateur_role_utilisateur
    FOREIGN KEY (utilisateur_id) REFERENCES utilisateur (id);